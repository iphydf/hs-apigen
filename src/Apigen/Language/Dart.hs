-- | One toxav callback, e.g. @toxav_call_cb@, as an event.
data AvCallback = AvCallback
    { avEvent  :: Event
    , avStem   :: Text            -- ^ @call@, after @toxav_callback_@.
    , avParams :: [(Text, Text, Text)]
      -- ^ Every parameter's name, native type and Dart type.
    }

-- | The callbacks registered with @toxav_callback_*@, which take the ToxAV
-- first. The old group calls' audio callback isn't one.
avCallbacks :: [SCallbackTypeModel] -> [AvCallback]
avCallbacks = mapMaybe avCallback
  where
    avCallback cb = do
        stem <- Text.stripPrefix "toxav_" (cbCName cb) >>= Text.stripSuffix "_cb"
        SHandle "AV" : _ <- Just (map paramType (cbParams cb))
        params <- mapM param (cbParams cb)
        pure $ AvCallback (Event stem (camel stem) (mapMaybe field (cbParams cb))) stem params
    param p = do
        (native, dart) <- types (paramType p)
        pure (camel (paramName p), native, dart)
    types ty = case ty of
        SHandle "AV"             -> Just ("Pointer<ToxAV>", "Pointer<ToxAV>")
        SHandle _                -> Just ("Pointer<Void>", "Pointer<Void>")
        SBool                    -> Just ("Bool", "bool")
        SUInt n                  -> Just ("Uint" <> tshow n, "int")
        SInt n                   -> Just ("Int" <> tshow n, "int")
        SSizeT                   -> Just ("Size", "int")
        SFixedList (SInt 16) _ _ -> Just ("Pointer<Int16>", "Pointer<Int16>")
        SFixedBytes _ _          -> Just ("Pointer<Uint8>", "Pointer<Uint8>")
        _                        -> Nothing
    -- The event keeps a copy of what the pointers point to.
    field p = let name = camel (paramName p) in case paramType p of
        SHandle _ -> Nothing
        SBool     -> Just (Field name "bool" (Atom name))
        SFixedList (SInt 16) size _ -> Just (Field name "Int16List" (copy "Int16List" name size))
        SFixedBytes size _          -> Just (Field name "Uint8List" (copy "Uint8List" name size))
        _         -> Just (Field name "int" (Atom name))
    copy list name size = Call (list <> ".fromList")
        [("", Call (name <> ".asTypedList") [("", Atom (sizeExpr size))])]

-- | A C size expression, such as @max(width, abs(ystride)) * height@, in Dart.
sizeExpr :: Text -> Text
sizeExpr = Text.concat . map word . Text.groupBy (\a b -> ident a == ident b)
  where
    ident c = isAlphaNum c || c == '_'
    word w
        | w == "abs" = "_abs"
        | w == "max" = w
        | Text.all ident w && not (isDigit (Text.head w)) = camel w
        | otherwise = Text.replace "/" "~/" w

