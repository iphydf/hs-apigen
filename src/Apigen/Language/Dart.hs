    register cb =
        layout 4 ("final " <> evName (avEvent cb) <> " = ")
            (Call ("NativeCallable<" <> typedefName cb <> ">.isolateLocal")
                [("", Atom ("_" <> evName (avEvent cb)))]) ";"
