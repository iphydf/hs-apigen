-- | A settable option: its Dart field, type, and the statements setting it.
data Option = Option Text Text [Text]

-- | Every option with a plain value. Owned data is always on, so toxcore
-- copies strings and bytes, and callbacks aren't supported.
options :: SemanticModel -> [Option]
options model = case List.find ((== "Options") . resourceName) (resources model) of
    Nothing  -> []
    Just res -> mapMaybe option (properties res)
  where
    option p = case (propWrite p, propType p) of
        (Just set, ty)
            | propName p /= "experimental_owned_data" -> do
                dartTy <- valueType ty
                let name = camel (propName p)
                    call args = layout 8 "" (Call ("lib.ffi." <> set) (("", Atom "options") : args)) ";"
                    owned arg len = layout 8 "" (Call "_owned"
                        [("", Call ("lib.ffi." <> set) [("", Atom "options"), ("", arg), ("", len)])]) ";"
                    stmts = case ty of
                        SString -> layout 8 "" (Call "_owned"
                            [("", Call ("lib.ffi." <> set) [("", Atom "options"), ("", Atom "copy(utf8.encode('$value\\u0000')).cast()")])]) ";"
                        SBytes  -> owned (Atom "copy(value)") (Atom "value.length")
                        _       -> call [("", Atom "value")]
                pure $ Option name dartTy stmts
        _ -> Nothing
    valueType ty = case ty of
        SBool   -> Just "bool"
        SUInt _ -> Just "int"
        SInt _  -> Just "int"
        SEnum n -> Just (enumCName model n)
        SString -> Just "String"
        SBytes  -> Just "Uint8List"
        _       -> Nothing

