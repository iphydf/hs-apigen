-- | Dart binding generator for bTox. Toxcore packs an event's fields in the
-- order of its @tox_events.h@ getters: alone if there is one, otherwise as an
-- array. Only @tox_av_callbacks.dart@ uses @dart:ffi@, which the web lacks.
module Apigen.Language.Dart (generate) where

import           Apigen.Semantic
import           Data.Char       (isAlphaNum, isDigit)
import qualified Data.List       as List
import           Data.Maybe      (fromMaybe, isJust, mapMaybe)
import           Data.Text       (Text)
import qualified Data.Text       as Text

generate :: SemanticModel -> [(FilePath, Text)]
generate model =
    [ ("tox_api.dart", genApi model)
    , ("tox_constants.dart", genConstants model)
    , ("tox_events.dart", genEvents model)
    , ("tox_options.dart", genOptions model)
    , ("tox_av_events.dart", genAvEvents model)
    , ("tox_av_callbacks.dart", genAvCallbacks model)
    ]

genConstants :: SemanticModel -> Text
genConstants model = Text.unlines $
    "// Generated by hs-apigen from the c-toxcore headers. Do not edit."
    : [ "const " <> camel (constantName c) <> " = " <> tshow (constantValue c) <> ";"
      | c <- constants model ]

