-- | A Dart parameter or return type, with how to pass and read it.
data DartType = DartType
    { dtName  :: Text
    , dtPass  :: Text -> Text   -- ^ The C argument for a Dart value.
    , dtRead  :: Text -> Text   -- ^ The Dart value of bytes read into @out@.
    , dtBytes :: Bool           -- ^ Passed as a buffer with a length.
    }

plain :: Text -> DartType
plain n = DartType n id id False

dartType :: SemanticModel -> SType -> Maybe DartType
dartType model ty = case ty of
    SBool         -> Just (plain "bool")
    SInt _        -> Just (plain "int")
    SUInt _       -> Just (plain "int")
    SSizeT        -> Just (plain "int")
    SResourceId _ -> Just (plain "int")
    SEnum n       -> Just (plain (enumCName model n))
    SString       -> Just (DartType "String" (\v -> "a.string(" <> v <> ")") id False)
    SBytes        -> Just (DartType "Uint8List" (\v -> "a.bytes(" <> v <> ")") id True)
    SFixedBytes size _ -> Just $ case lookup size keyTypes of
        Just key -> DartType key (\v -> "a.bytes(" <> v <> ".bytes)") (\v -> key <> "(" <> v <> ")") False
        Nothing  -> DartType "Uint8List" (\v -> "a.bytes(" <> v <> ")") id False
    SList (SResourceId _) -> Just (plain "List<int>")
    SFixedList (SInt 16) _ _ -> Just (DartType "Int16List" (\v -> "a.int16s(" <> v <> ")") id False)
    _             -> Nothing
  where
    keyTypes =
        [ ("TOX_ADDRESS_SIZE", "ToxAddress")
        , ("TOX_DHT_ID_SIZE", "PublicKey")
        , ("TOX_PUBLIC_KEY_SIZE", "PublicKey")
        , ("TOX_SECRET_KEY_SIZE", "SecretKey")
        ]

-- | One generated method.
data ApiMethod = ApiMethod
    { amSignature :: (Text, Text, [(Text, Text)])  -- ^ Return type, name, parameters.
    , amBody      :: [Text]                         -- ^ Statements, at 4 spaces.
    }

-- | toxav's functions, apart from creating, iterating and killing a ToxAV.
avResources :: [Text]
avResources = ["AV"]

apiMethods :: [Text] -> SemanticModel -> [ApiMethod]
apiMethods names model =
    [ m | res <- resources model, resourceName res `elem` names
        , let sizeFns = [s | CustomMapping cm <- map methodMapping (methods res), Just s <- [cSizeFunctionName cm]]
        , meth <- methods res
        , methodRole meth `elem` [ActionRole, Constructor]
        , methodName meth `notElem` sizeFns
        , Just m <- [apiMethod model res meth] ]

-- | The parameter names of a resource's ids, outermost first.
idNames :: SemanticModel -> SResource -> [Text]
idNames model res = reverse (go res)
  where
    go r = case parent r of
        Nothing -> []
        Just p  -> camel (resourceName r <> "_Number")
                   : maybe [] go (List.find ((== p) . resourceName) (resources model))

apiMethod :: SemanticModel -> SResource -> SMethod -> Maybe ApiMethod
apiMethod model res meth = do
    CustomMapping cm <- Just (methodMapping meth)
    inTypes <- mapM (dartType model . paramType) (inputs meth)
    let ids = idNames model res
        inNames = map (camel . paramName) (inputs meth)
        bufferOut = any isBuffer (argMapping cm)
        isBuffer (BufferPtr _) = True
        isBuffer _             = False
        ignore = methodResultStrategy meth == IgnoreReturn || output meth == SVoid
    outType <- if ignore then Just Nothing else Just <$> dartType model (output meth)
    let errorCheck fn = case methodErrorType meth of
            Nothing -> []
            Just e  -> layout 6 "" (Call "_check"
                [ ("", Call (e <> ".fromValue") [("", Atom "err.value")])
                , ("", Atom ("'" <> fn <> "'"))
                ]) ";"
        args mapping = go mapping Nothing
          where
            go [] _ = []
            go (a : as) lastBytes = case a of
                ThisObject _   -> Atom "pointer" : go as lastBytes
                PathObject _ _ -> Atom "pointer" : go as lastBytes
                PathId n       -> Atom (ids !! (n - 1)) : go as lastBytes
                SemanticArg i  ->
                    let t = inTypes !! i; v = inNames !! i
                    in Atom (dtPass t v) : go as (if dtBytes t then Just v else lastBytes)
                BufferSize     -> Atom (fromMaybe "0" lastBytes <> ".length") : go as lastBytes
                BufferPtr _    -> Atom "out" : go as lastBytes
                ErrorPtr       -> Atom "err" : go as lastBytes
                _              -> Atom "null" : go as lastBytes
        call fn mapping = Call ("lib.ffi." <> fn) [("", e) | e <- args mapping]
        sizeMethod = cSizeFunctionName cm >>= \s -> List.find ((== s) . methodName) (methods res)
        sizeArgs = case sizeMethod >>= \sm -> case methodMapping sm of
                        CustomMapping scm -> Just (argMapping scm)
                        _                 -> Nothing of
            Just m  -> m
            Nothing -> []
        needsArena = isJust (methodErrorType meth) || bufferOut || any (\t -> dtName t `elem` ["String", "Uint8List", "Int16List", "PublicKey", "ToxAddress", "SecretKey"]) inTypes
        bufferSize = case [s | BufferPtr (Just s) <- argMapping cm] of
            s : _ -> Just (camel s)
            []    -> Nothing
        outBody = case output meth of
            SList _ -> ["      final out = a.ids(size);"]
            _       -> ["      final out = a.buffer(" <> fromMaybe "size" bufferSize <> ");"]
        sizeBody = case (bufferSize, sizeMethod) of
            (Nothing, Just sm) ->
                layout 6 "final size = " (call (methodName sm) sizeArgs) ";"
                ++ (case methodErrorType sm of
                        Nothing -> []
                        Just _  -> errorCheck (methodName sm))
            _ -> []
        readOut = case output meth of
            SList _ -> "out.asTypedList(size).toList()"
            _       -> maybe "_read(out, size)" (\t -> dtRead t ("_read(out, " <> fromMaybe "size" bufferSize <> ")")) outType
        result = case (bufferOut, outType) of
            (True, _) ->
                sizeBody ++ outBody
                ++ layout 6 "" (call (methodName meth) (argMapping cm)) ";"
                ++ errorCheck (methodName meth)
                ++ ["      return " <> readOut <> ";"]
            (False, Nothing) ->
                layout 6 "" (call (methodName meth) (argMapping cm)) ";"
                ++ errorCheck (methodName meth)
            (False, Just _)
                | isJust (methodErrorType meth) ->
                    layout 6 "final result = " (call (methodName meth) (argMapping cm)) ";"
                    ++ errorCheck (methodName meth)
                    ++ ["      return result;"]
                | otherwise -> layout 6 "return " (call (methodName meth) (argMapping cm)) ";"
        body
            | needsArena =
                [ "    final a = _Arena(lib);", "    try {" ]
                ++ [ "      final err = a.error();" | isJust (methodErrorType meth) ]
                ++ result
                ++ [ "    } finally {", "      a.free();", "    }" ]
            | otherwise = map (Text.drop 2) result
        name = camel (fromMaybe (methodName meth) (List.find (`Text.isPrefixOf` methodName meth) ["toxav_", "tox_"] >>= (`Text.stripPrefix` methodName meth)))
        params = [(i, "int") | i <- take (length [() | PathId _ <- argMapping cm]) ids]
                 ++ zip inNames (map dtName inTypes)
    pure $ ApiMethod (maybe "void" dtName outType, name, params) body

-- | A method declaration, laid out like @dart format@.
signature :: Text -> (Text, Text, [(Text, Text)]) -> [Text]
signature end (ret, name, params)
    | fits line = [line]
    | otherwise = ["  " <> ret <> " " <> name <> "("]
                  ++ ["    " <> t <> " " <> n <> "," | (n, t) <- params]
                  ++ ["  )" <> end]
  where
    line = "  " <> ret <> " " <> name <> "(" <> Text.intercalate ", " [t <> " " <> n | (n, t) <- params] <> ")" <> end

